import bwipjs from "bwip-js/browser";
import { useMemo } from "react";
import { cn } from "@/lib/utils";

export type LabelFormat = "code128" | "qrcode";

/** A barcode drawn as SVG, so it stays sharp at any print size. Falls back to plain text if the code can't be encoded. */
export function BarcodeSvg({ text, format, className }: { text: string; format: LabelFormat; className?: string }) {
  const svg = useMemo(() => {
    try {
      return bwipjs.toSVG({
        bcid: format,
        text,
        ...(format === "code128" ? { height: 12, includetext: false, paddingwidth: 0, paddingheight: 0 } : { paddingwidth: 0, paddingheight: 0 }),
      });
    } catch {
      return null;
    }
  }, [text, format]);
  if (!svg) return <p className="font-mono text-xs text-destructive">Can't encode "{text}"</p>;
  return (
    <div
      role="img"
      aria-label={`${format === "qrcode" ? "QR code" : "Barcode"} for ${text}`}
      className={cn("[&>svg]:h-full [&>svg]:w-full", className)}
      // The SVG is generated by bwip-js from our own text; it contains only shapes.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
